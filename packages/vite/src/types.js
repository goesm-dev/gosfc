// The TypeScript types of go: imports.
//
// goesm (after v0.0.1-beta.7) writes a declaration file of each entry
// package's exports (emit-ts -dts), which imports no other file. gosfc
// declares each package JavaScript imports with go: as an ambient module
// of that name in one file:
//
//   declare module "go:example.com/app/cart" {
//     export function Total(items: Array<{ name?: string; price?: number }> | null): number;
//   }
//
// The plugin rewrites the file whenever a compilation changes it; Astro
// references it from .astro/types.d.ts (@gosfc/astro), and a Vite project
// includes it in its tsconfig.json. Until Go has been compiled, the file
// declares every go: import as any.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { scanGoModule } from "./compile.js";
import { findGoModule } from "./gomod.js";
import { GoProgram } from "./program.js";

const HEADER = "// Generated by gosfc: the types of the Go packages JavaScript imports with go:. DO NOT EDIT.\n";

/** The file before any Go has been compiled: every go: import is any. */
export const PLACEHOLDER = HEADER + "// No Go has been compiled yet: a dev server, a build or astro sync writes the types.\ndeclare module \"go:*\";\n";

/**
 * The declarations of the packages the programs' JavaScript imports with
 * go:, or null when there are none (or goesm writes no declaration files).
 * @param {Iterable<GoProgram>} programs
 * @returns {string | null}
 */
export function goImportTypes(programs) {
  /** @type {Map<string, string>} */
  const decls = new Map();
  for (const p of programs) {
    const o = p.outcome;
    if (!o || o.error) continue;
    const imported = new Set(p.imports);
    for (const m of o.modules) if (m.dts && imported.has(m.importPath)) decls.set(m.importPath, m.dts);
  }
  if (!decls.size) return null;
  let out = HEADER;
  for (const importPath of [...decls.keys()].sort()) {
    const body = decls
      .get(importPath)
      .split("\n")
      .filter((l) => l && !l.startsWith("//"))
      .map((l) => "  " + l)
      .join("\n");
    out += `\ndeclare module ${JSON.stringify("go:" + importPath)} {\n${body}\n}\n`;
  }
  return out;
}

/**
 * Writes content to file unless it already holds it.
 * @param {string} file
 * @param {string} content
 */
export function writeTypes(file, content) {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
}

/**
 * Compiles the Go of the app at root as a scan finds it, as the plugin's
 * first compilation does, and returns the types of its go: imports (null
 * when there are none).
 * @param {string} root
 * @param {string[]} [outDirs] directories the scan skips
 * @returns {Promise<string | null>}
 */
export async function scanGoImportTypes(root, outDirs = []) {
  root = path.resolve(root);
  outDirs = outDirs.map((d) => path.resolve(d));
  const mod = findGoModule(root);
  if (!mod) return null;
  const p = new GoProgram(mod, () => scanGoModule(root, mod, outDirs));
  await p.ready;
  await p.compile();
  return goImportTypes([p]);
}
